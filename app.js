let resolvePlacesReady;
window.placesDataPromise = new Promise((resolve) => {
  resolvePlacesReady = resolve;
});

window.getPlacesData = function () {
  return window.placesDataPromise;
};

function initData() {
  resolvePlacesReady(window.Sho1re1Places);
  window.dispatchEvent(
    new CustomEvent('placesReady', { detail: window.Sho1re1Places })
  );
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initData);
} else {
  initData();
}
